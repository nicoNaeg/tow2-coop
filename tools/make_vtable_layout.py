"""Build UE4SS's VTableLayout.ini for The Outer Worlds 2 (Steam 1.2.0.1, UE 5.4.4) from UE4SS's stock 5.4
template plus the two virtuals this engine branch adds before UObject::ProcessEvent (same two as
S.T.A.L.K.E.R. 2's UE4SS config): UObjectBaseUtility::GetVersePath and UObject::CollectSaveOverrides.
Measured on the game: ProcessEvent is vtable slot 79 (stock 5.4: 77).
Usage: python -I make_vtable_layout.py <VTableLayout_5_04_Template.ini> <out VTableLayout.ini>"""
import sys

INSERTS = {  # section -> (insert after this entry, new entry, its signature comment)
    "UObjectBaseUtility": ("OnClusterMarkedAsPendingKill", "GetVersePath", "; UE::Core::FVersePath GetVersePath() const"),
    "UObject": ("PreSave__Ptr_C_ITargetPlatform", "CollectSaveOverrides", "; void CollectSaveOverrides(FObjectCollectSaveOverridesContext)"),
}


def build(lines):
    out, section, done = [], None, set()
    for line in lines:
        out.append(line)
        s = line.strip()
        if s.startswith("[") and s.endswith("]"):
            section = s[1:-1]
        elif section in INSERTS and s == INSERTS[section][0]:
            _, name, sig = INSERTS[section]
            out += [sig, name]
            done.add(section)
    missing = set(INSERTS) - done
    if missing:
        raise SystemExit(f"anchor not found in sections {sorted(missing)}: template changed?")
    return out


def slot(lines, name):
    """Slot of `name` across the UObject chain (the shared destructor is slot 0)."""
    n, section = 0, None
    for line in lines:
        s = line.strip()
        if s.startswith("["):
            section = s[1:-1]
        elif section in ("UObjectBase", "UObjectBaseUtility", "UObject") and s and not s.startswith(";") and s != "__vecDelDtor":
            n += 1
            if s == name:
                return n
    return None


if __name__ == "__main__":
    src = open(sys.argv[1], encoding="utf-8-sig").read().splitlines()
    out = build(src)
    assert slot(src, "ProcessEvent") == 77, slot(src, "ProcessEvent")  # stock 5.4
    assert slot(out, "ProcessEvent") == 79, slot(out, "ProcessEvent")  # measured on the game
    header = ["; The Outer Worlds 2 (Steam 1.2.0.1, UE 5.4.4): stock 5.4 layout + GetVersePath + CollectSaveOverrides.",
              "; Generated by make_vtable_layout.py; ProcessEvent measured at UObject vtable slot 79."]
    open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(header + out) + "\n")
    print(f"wrote {sys.argv[2]}: ProcessEvent slot {slot(out, 'ProcessEvent')}, GetWorld slot {slot(out, 'GetWorld')}, "
          f"ProcessConsoleExec slot {slot(out, 'ProcessConsoleExec')}")
